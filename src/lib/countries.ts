/** Iran: the nationality of every national ID, never of a foreign national. */
export const IRAN = "IR";

export interface Country {
  code: string;
  name: string;
}

/** A country's name in `locale`, or the code itself if the browser has none. */
export function countryName(code: string, locale: string | undefined): string {
  try {
    return new Intl.DisplayNames(locale ? [locale] : [], { type: "region" }).of(code) ?? code;
  } catch {
    return code;
  }
}

/** Every country but Iran, by name in `locale`: the nationalities of foreign nationals. */
export function foreignCountries(locale: string | undefined): Country[] {
  const names = new Intl.DisplayNames(locale ? [locale] : [], { type: "region" });
  const collator = new Intl.Collator(locale);
  return COUNTRY_CODES.filter((code) => code !== IRAN)
    .map((code) => ({ code, name: names.of(code) ?? code }))
    .sort((a, b) => collator.compare(a.name, b.name));
}
